#!/usr/bin/env node
// build.mjs — `astro build` → dist/, then Pagefind index, then the edge config
// (_headers + nginx.conf) with Cache-Control and Cache-Tag per page.
import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { parse } from 'node-html-parser';
import { config, ROOT } from './lib/config.mjs';
import { readJson, writeJson, log, dirSize, parseArgs } from './lib/util.mjs';

const HTML_CACHE = 'public, max-age=60, s-maxage=300, stale-while-revalidate=3600';
const IMMUTABLE = 'public, max-age=31536000, immutable';

function run(cmd, args, cwd) {
  const r = spawnSync(cmd, args, { cwd, stdio: 'inherit', env: { ...process.env, PUBLIC_URL: config.publicUrl }, shell: process.platform === 'win32' });
  if (r.status !== 0) throw new Error(`${cmd} ${args.join(' ')} exited with ${r.status}`);
}

// Walk dist/ and collect every HTML page with the cache tags the template put in <meta name="cache-tag">.
function collectPages(dist) {
  const out = [];
  const walk = (dir) => {
    for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
      const p = path.join(dir, e.name);
      if (e.isDirectory()) walk(p);
      else if (e.name.endsWith('.html')) {
        const rel = '/' + path.relative(dist, p).replace(/\\/g, '/').replace(/index\.html$/, '');
        const tags = parse(fs.readFileSync(p, 'utf8')).querySelector('meta[name="cache-tag"]')?.getAttribute('content') ?? 'page';
        out.push({ path: rel, file: p, bytes: fs.statSync(p).size, tags: tags.split(',') });
      }
    }
  };
  walk(dist);
  return out.sort((a, b) => a.path.localeCompare(b.path));
}

function writeEdgeConfig(dist, pages) {
  // Netlify / Cloudflare Pages style
  const lines = ['# generated by pipeline/build.mjs', '/_astro/*', `  Cache-Control: ${IMMUTABLE}`, '/pagefind/*', `  Cache-Control: ${IMMUTABLE}`, ''];
  for (const p of pages) lines.push(p.path === '/404/' ? '/404.html' : p.path, `  Cache-Control: ${HTML_CACHE}`, `  Cache-Tag: ${p.tags.join(',')}`, `  Surrogate-Key: ${p.tags.join(' ')}`, '');
  fs.writeFileSync(path.join(dist, '_headers'), lines.join('\n'));

  // nginx snippet: hashed assets immutable, HTML short TTL + tag header via map
  const mapLines = pages.map((p) => `    ${p.path === '/404/' ? '/404.html' : p.path} "${p.tags.join(' ')}";`).join('\n');
  fs.writeFileSync(path.join(dist, 'nginx.conf'), `# generated by pipeline/build.mjs — include inside http {} and server {}
map $uri $surrogate_key {
    default "page";
${mapLines}
}
server {
    root ${dist};
    index index.html;
    error_page 404 /404.html;
    location /_astro/  { add_header Cache-Control "${IMMUTABLE}"; }
    location /pagefind/ { add_header Cache-Control "${IMMUTABLE}"; }
    location / {
        try_files $uri $uri/index.html =404;
        add_header Cache-Control "${HTML_CACHE}";
        add_header Surrogate-Key $surrogate_key;
        add_header Cache-Tag $surrogate_key;
    }
}
`);
}

export function build(flags = {}) {
  const info = readJson(config.files.buildInfo, {});
  if (info.skipBuild && !flags.force) { log('build: skipped (no changes)'); return { skipped: true }; }
  const prev = dirSize(config.dirs.dist);
  const t0 = Date.now();
  log('build: astro build');
  run(path.join(ROOT, 'node_modules', '.bin', 'astro'), ['build'], config.dirs.site);
  log('build: pagefind index');
  run(path.join(ROOT, 'node_modules', '.bin', 'pagefind'), ['--site', config.dirs.dist, '--quiet'], ROOT);
  for (const f of ['content-assets.mjs', 'content-modules.mjs']) fs.rmSync(path.join(config.dirs.dist, f), { force: true }); // Astro content-layer leftovers
  const pages = collectPages(config.dirs.dist);
  writeEdgeConfig(config.dirs.dist, pages);
  const size = dirSize(config.dirs.dist);
  const result = { skipped: false, seconds: (Date.now() - t0) / 1000, pages: pages.length, distBytes: size.bytes, distFiles: size.files, prevDistBytes: prev.bytes, pageList: pages.map(({ path: p, bytes, tags }) => ({ path: p, bytes, tags })), at: new Date().toISOString() };
  writeJson(path.join(ROOT, 'content', 'build-result.json'), result);
  log(`build: ${pages.length} pages in ${result.seconds.toFixed(1)}s, dist ${(size.bytes / 1e6).toFixed(2)} MB`);
  return result;
}

if (import.meta.url === `file://${process.argv[1]}`) build(parseArgs());
