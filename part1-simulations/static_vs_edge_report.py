"""static_vs_edge_report.py — the tables of results/STATIC-VS-EDGE.md (static-vs-edge.sh).

Reads results/stress/<LADDER>/ (steps.csv, step-<rate>.summary.json, step-<rate>.stats.csv)
for the four ladders and prints, per step: throughput, p95, errors, and the CPU of the
server that answered (nginx or Varnish) and of k6. Then one line per ladder at its
clean capacity (the last step with < 1 % dropped, < 1 % errors).

    python3 static_vs_edge_report.py            → results/STATIC-VS-EDGE.steps.md
"""
import csv
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.join(HERE, "results")
LADDERS = [  # label, server container, unit
    ("S6-static-pages", "proventeq-fidelity", "req"),
    ("S4-edge-pages-r2", "liferay-varnish", "req"),
    ("S6-static-pageview", "proventeq-fidelity", "view"),
    ("S4-edge-pageview", "liferay-varnish", "view"),
]


def p90(rows, col):
    xs = sorted(float(r[col]) for r in rows if r.get(col))
    return xs[max(0, int(len(xs) * 0.9) - 1)] if xs else 0.0


def steps(label, server, unit):
    d = os.path.join(RES, "stress", label)
    if not os.path.exists(os.path.join(d, "steps.csv")):
        return []
    out = []
    for row in csv.DictReader(open(os.path.join(d, "steps.csv"))):
        rate = row["target_rate"]
        m = json.load(open(os.path.join(d, f"step-{rate}.summary.json")))["metrics"]
        stats = list(csv.DictReader(open(os.path.join(d, f"step-{rate}.stats.csv"))))
        view = m.get("page_view_duration", {}).get("values", {})
        received = m.get("data_received", {}).get("values", {}).get("rate", 0)
        out.append({
            "rate": int(rate),
            "it_s": float(row["achieved_iter_s"]),
            "req_s": float(row["req_s"]),
            "drop": float(row["dropped_pct"]),
            "err": float(row["error_pct"]),
            "p95": float(row["p95_ms"]),
            "view_p95": view.get("p(95)") if unit == "view" else None,
            "server": p90(stats, f"{server}_cores"),
            "liferay": p90(stats, "liferay26112_cores"),
            "k6": p90(stats, "k6_cores"),
            "host": p90(stats, "host_cores"),
            "mb_s": received / 1e6,
        })
    return out


lines = ["# Static vs Varnish: every step", "",
         "Generated by `static_vs_edge_report.py` from `results/stress/<ladder>/`. Cores are p90 over the step.", ""]
summary = []
for label, server, unit in LADDERS:
    rows = steps(label, server, unit)
    if not rows:
        continue
    lines += [f"## {label}", "",
              f"| target {unit}/s | achieved {unit}/s | req/s | MB/s received | dropped | errors | p95 request | p95 page view | {server} cores | Liferay cores | k6 cores | host cores |",
              "|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|"]
    for r in rows:
        v = f"{r['view_p95']:.0f} ms" if r["view_p95"] is not None else "–"
        lines.append(f"| {r['rate']:,} | {r['it_s']:,.0f} | {r['req_s']:,.0f} | {r['mb_s']:,.0f} | {r['drop']:.1f} % | {r['err']:.2f} % | "
                     f"{r['p95']:.1f} ms | {v} | {r['server']:.1f} | {r['liferay']:.1f} | {r['k6']:.1f} | {r['host']:.1f} |")
    lines.append("")
    clean = [r for r in rows if r["drop"] < 1 and r["err"] < 1]
    if clean:
        c = clean[-1]
        summary.append(f"{label:20} clean {c['it_s']:8,.0f} {unit}/s  {c['req_s']:8,.0f} req/s  p95 {c['p95']:6.1f} ms"
                       f"  view p95 {c['view_p95'] or 0:6.0f} ms  {server} {c['server']:4.1f} cores"
                       f"  ({1000 * c['server'] / max(1, c['it_s']):.3f} ms CPU per {unit})  k6 {c['k6']:4.1f}  host {c['host']:4.1f}")

open(os.path.join(RES, "STATIC-VS-EDGE.steps.md"), "w").write("\n".join(lines))
print("\n".join(summary))
