#!/usr/bin/env bash
#
# apply-stage.sh — layer S1…S3 onto the local Docker Liferay used for the measured runs
# (liferay/dxp:2026.q1.12-lts, single node, Hypersonic + sidecar Elasticsearch).
#
#   ./apply-stage.sh S0|S1|S2|S3      # cumulative: S2 = S1 + S2, S3 = S1 + S2 + S3
#
# Only what is meaningful on ONE node with Hypersonic is applied. Skipped, on purpose:
#   S2  Cluster Link / JDBC_PING (no second node, no MySQL) — see ../S2-jvm-caches
#   S3  cdn.host.* (no CDN in this lab; pointing it at cdn.example.com breaks every asset)
#   S4  web.server.protocol=https / ports (Varnish here is plain HTTP on :6081)
# The originals of setenv.sh and server.xml are in ./original/ (S0 restores them).
# Fragment "Cacheable" (S2) is a database flag: set for S2+, cleared for S0/S1, via JSONWS.
#
# Env: CONTAINER (liferay26112), BASE_URL (http://127.0.0.1:8086), SITE_ID (34961), LIFERAY_USER/LIFERAY_PASSWORD
set -euo pipefail
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
MATRIX="$(cd "$HERE/.." && pwd)"
C="${CONTAINER:-liferay26112}"
BASE_URL="${BASE_URL:-http://127.0.0.1:8086}"
STAGE="${1:?usage: $0 S0|S1|S2|S3}"
L=/opt/liferay
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

level() { case "$1" in S0) echo 0;; S1) echo 1;; S2) echo 2;; S3) echo 3;; *) echo "unknown stage $1" >&2; exit 1;; esac; }
N=$(level "$STAGE")

# ---- portal-ext.properties (cumulative) --------------------------------------
{
	echo "## generated by part1-simulations/matrix/local/apply-stage.sh $STAGE — $(date -Is)"
	if (( N >= 1 )); then
		echo; echo "## --- S1 hygiene (../S1-hygiene/portal-ext.properties, all lines)"
		grep -vE '^\s*(#|$)' "$MATRIX/S1-hygiene/portal-ext.properties"
	fi
	if (( N >= 2 )); then
		echo; echo "## --- S2 JVM caches (Ehcache 3 override + HikariCP + Hibernate; Cluster Link skipped: single node)"
		grep -vE '^\s*(#|$)' "$MATRIX/S2-jvm-caches/portal-ext.properties" | grep -v '^cluster\.link'
	fi
	if (( N >= 3 )); then
		echo; echo "## --- S3 front-end delivery (browser cache for guest HTML; cdn.host.* skipped: no CDN here)"
		grep -vE '^\s*(#|$)' "$MATRIX/S3-frontend/portal-ext.properties" | grep -v '^cdn\.'
	fi
} > "$TMP/portal-ext.properties"

# ---- setenv.sh: container original + stage JVM flags appended (last flag wins) -----
cp "$HERE/original/setenv.sh" "$TMP/setenv.sh"
if (( N == 1 )); then
	cat >> "$TMP/setenv.sh" <<'EOF'

# --- S1 hygiene (../S1-hygiene/setenv.sh): explicit heap, G1, GC log, OOM diagnostics
CATALINA_OPTS="$CATALINA_OPTS -Xms4096m -Xmx4096m -XX:MetaspaceSize=768m -XX:MaxMetaspaceSize=768m -XX:+UseG1GC -XX:MaxGCPauseMillis=200 -Xlog:gc*:file=/opt/liferay/logs/gc.log:time,uptime,level,tags:filecount=5,filesize=50m -XX:+HeapDumpOnOutOfMemoryError -XX:HeapDumpPath=/opt/liferay/logs -XX:+ExitOnOutOfMemoryError"
EOF
elif (( N >= 2 )); then
	cat >> "$TMP/setenv.sh" <<EOF

# --- S2 JVM caches (../S2-jvm-caches/setenv.sh, GC=${GC:-g1}): 6 GB pre-touched heap, tuned G1 or Generational ZGC
GC_OPTS_S2="-XX:+UseG1GC -XX:MaxGCPauseMillis=200 -XX:G1HeapRegionSize=4m -XX:InitiatingHeapOccupancyPercent=45"
[ "${GC:-g1}" = "zgc" ] && GC_OPTS_S2="-XX:+UseZGC -XX:+ZGenerational -XX:SoftMaxHeapSize=5g"
CATALINA_OPTS="\$CATALINA_OPTS -Xms6g -Xmx6g -XX:MetaspaceSize=768m -XX:MaxMetaspaceSize=768m -XX:+AlwaysPreTouch \$GC_OPTS_S2 -Xlog:gc*:file=/opt/liferay/logs/gc-${GC:-g1}.log:time,uptime,level,tags:filecount=5,filesize=50m -XX:+HeapDumpOnOutOfMemoryError -XX:HeapDumpPath=/opt/liferay/logs -XX:+ExitOnOutOfMemoryError"
EOF
fi

# ---- server.xml: S2 connector shape (small pool, big backlog) ---------------------
cp "$HERE/original/server.xml" "$TMP/server.xml"
if (( N >= 2 )); then
	python3 - "$TMP/server.xml" <<'EOF'
import re, sys
p = sys.argv[1]; s = open(p).read()
new = '''<Connector port="8080" protocol="org.apache.coyote.http11.Http11NioProtocol"
               maxThreads="75" minSpareThreads="50" acceptCount="1000" maxConnections="16384"
               maxKeepAliveRequests="-1" connectionTimeout="20000" redirectPort="8443"
               maxParameterCount="1000" URIEncoding="UTF-8" compression="off" />'''
s, n = re.subn(r'<Connector maxThreads="75" port="8080" protocol="HTTP/1.1"[^>]*/>', new, s, count=1)
assert n == 1, "stock 8080 connector not found"
open(p, "w").write(s)
EOF
fi

# ---- push into the container ---------------------------------------------------------
docker cp "$TMP/portal-ext.properties" "$C:$L/portal-ext.properties"
docker cp "$TMP/setenv.sh" "$C:$L/tomcat/bin/setenv.sh"
docker cp "$TMP/server.xml" "$C:$L/tomcat/conf/server.xml"
docker exec "$C" sh -c "mkdir -p $L/tomcat/webapps/ROOT/WEB-INF/classes/ehcache"
if (( N >= 2 )); then
	docker cp "$MATRIX/S2-jvm-caches/liferay-multi-vm-override.xml" "$C:$L/tomcat/webapps/ROOT/WEB-INF/classes/ehcache/liferay-multi-vm-override.xml"
else
	docker exec "$C" rm -f "$L/tomcat/webapps/ROOT/WEB-INF/classes/ehcache/liferay-multi-vm-override.xml"
fi
DL_PID=com.liferay.document.library.web.internal.configuration.CacheControlConfiguration
if (( N >= 3 )); then
	docker cp "$MATRIX/S3-frontend/osgi-configs/$DL_PID.config" "$C:$L/osgi/configs/$DL_PID.config"
else
	docker exec "$C" rm -f "$L/osgi/configs/$DL_PID.config"
fi

# ---- restart and wait -------------------------------------------------------------------
echo "== $STAGE applied; restarting $C"
docker exec "$C" sh -c "cp $L/portal-ext.properties $L/logs/portal-ext.$STAGE.properties"
started=$(date +%s)
docker restart "$C" >/dev/null
until curl -sf -o /dev/null --max-time 5 "$BASE_URL/c/portal/robots" && curl -sf -o /dev/null --max-time 20 "$BASE_URL/web/proventeq/home"; do
	sleep 5
	if (( $(date +%s) - started > 600 )); then echo "!! portal not up after 10 min" >&2; exit 1; fi
done
echo "== up after $(( $(date +%s) - started )) s"

# ---- S2 fragment "Cacheable" flag: lives in the database, not in a config file -------------
# so it survives restarts and has to be set (S2+) or cleared (S0/S1) explicitly per stage.
CACHEABLE=$( (( N >= 2 )) && echo true || echo false )
JW="$BASE_URL/api/jsonws"; AUTH="${LIFERAY_USER:-test@liferay.com}:${LIFERAY_PASSWORD:-t}"
for coll in $(curl -s -u "$AUTH" "$JW/fragment.fragmentcollection/get-fragment-collections/group-id/${SITE_ID:-34961}" |
		python3 -c 'import json,sys; print(" ".join(str(c["fragmentCollectionId"]) for c in json.load(sys.stdin)))'); do
	for id in $(curl -s -u "$AUTH" "$JW/fragment.fragmententry/get-fragment-entries/fragment-collection-id/$coll" |
			python3 -c 'import json,sys; print(" ".join(str(e["fragmentEntryId"]) for e in json.load(sys.stdin)))'); do
		curl -s -o /dev/null -u "$AUTH" "$JW/fragment.fragmententry/update-fragment-entry/fragment-entry-id/$id/cacheable/$CACHEABLE"
	done
done
echo "== fragment cacheable flags now: $(for coll in $(curl -s -u "$AUTH" "$JW/fragment.fragmentcollection/get-fragment-collections/group-id/${SITE_ID:-34961}" |
		python3 -c 'import json,sys; print(" ".join(str(c["fragmentCollectionId"]) for c in json.load(sys.stdin)))'); do
	curl -s -u "$AUTH" "$JW/fragment.fragmententry/get-fragment-entries/fragment-collection-id/$coll"; done |
	python3 -c 'import json,sys,collections; print(dict(collections.Counter(e["cacheable"] for e in json.load(sys.stdin))))')"
