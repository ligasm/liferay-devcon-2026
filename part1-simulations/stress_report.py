"""stress_report.py — tables and charts for the capacity ladders (stress.sh).

Reads results/stress/<LABEL>/steps.csv, writes results/stress/STEPS.md (every step)
and three charts:
  results/stress-latency-vs-throughput.png   guest pages: p95 vs achieved req/s (S0, S3, S4)
  results/stress-mix-slowest-flow.png        mixed workload: slowest flow's p95 vs achieved req/s
  results/stress-capacity.png                clean capacity + peak throughput per ladder
  results/stress-origin-cpu.png              Liferay CPU vs achieved req/s (origin ladders)
Needs matplotlib.   python3 stress_report.py
"""
import csv
import json
import glob
import os

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.join(HERE, "results")
SURFACE, INK, INK2, GRID = "#fcfcfb", "#0b0b0b", "#52514e", "#e4e3df"
SERIES = ["#2a78d6", "#eb6834", "#1baf7a", "#8a5cd1", "#c2417a", "#7a7a2e"]

ladders = {}
for path in sorted(glob.glob(os.path.join(RES, "stress", "*", "steps.csv"))):
    if os.path.basename(os.path.dirname(path)).startswith("_"):  # warm-ups, probes, invalidated runs
        continue
    rows = list(csv.DictReader(open(path)))
    if rows:  # refinement steps are appended later — order by target rate
        ladders[rows[0]["label"]] = sorted(rows, key=lambda r: float(r["target_rate"]))

NAMES = {
    "S0-origin-pages": "S0 stock origin · guest pages", "S3-origin-pages": "S3 tuned origin · guest pages",
    "S4-edge-pages": "S4 Varnish edge · guest pages (k6 full checks)",
    "S4-edge-pages-light": "S4 Varnish edge · guest pages (k6 light)", "S0-origin-mix": "S0 stock origin · mix",
    "S3-origin-mix": "S3 tuned origin · mix", "S4-edge-mix": "S4 Varnish edge · mix",
    "S3-origin-search": "S3 tuned origin · search", "S3-origin-login": "S3 tuned origin · login",
}
ORDER = [k for k in NAMES if k in ladders] + [k for k in ladders if k not in NAMES]
f = lambda r, k: float(r[k])


def worst_flow_p95(label, rate):
    """Highest per-flow p95 of one step (login can time out while cached pages stay fast)."""
    sj = os.path.join(RES, "stress", label, f"step-{rate}.summary.json")
    if not os.path.exists(sj):
        return 0
    m = json.load(open(sj))["metrics"]
    return max([v["values"].get("p(95)", 0) for k, v in m.items() if k.startswith("http_req_duration{page:")] or [0])


def clean(rows):
    """Clean capacity = last step before the first one that misses the bar:
    < 1 % dropped, < 1 % errors, every flow's p95 < 2 s."""
    best = None
    for r in rows:
        if f(r, "dropped_pct") >= 1 or f(r, "error_pct") >= 1 or worst_flow_p95(r["label"], r["target_rate"]) >= 2000:
            break
        best = r
    return best


def peak(rows):
    """Highest throughput reached in any step with < 1 % errors."""
    ok = [r for r in rows if f(r, "error_pct") < 1]
    return max(ok, key=lambda r: f(r, "req_s")) if ok else None


UNIT = {"login": "sign-ins/s", "search": "searches/s"}


def style(ax, title, xlabel, ylabel=None):
    ax.set_facecolor(SURFACE)
    ax.set_title(title, loc="left", fontsize=13, color=INK, fontweight="bold", pad=14)
    ax.set_xlabel(xlabel, color=INK2, fontsize=10)
    if ylabel:
        ax.set_ylabel(ylabel, color=INK2, fontsize=10)
    ax.tick_params(colors=INK2, labelsize=10, length=0)
    for side in ("top", "right"):
        ax.spines[side].set_visible(False)
    for side in ("bottom", "left"):
        ax.spines[side].set_color(GRID)
    ax.grid(True, color=GRID, linewidth=0.8)
    ax.set_axisbelow(True)


def save(fig, name):
    fig.patch.set_facecolor(SURFACE)
    fig.tight_layout()
    fig.savefig(os.path.join(RES, name), dpi=160, facecolor=SURFACE, bbox_inches="tight", pad_inches=0.25)
    print("wrote results/" + name)


# ---- STEPS.md ---------------------------------------------------------------------------
md = ["# Capacity ladders — every step", "", "Generated by `stress_report.py` from `results/stress/*/steps.csv`.", ""]
for k in ORDER:
    md += [f"## {NAMES.get(k, k)} (`{k}`)", "",
           "| target it/s | achieved it/s | req/s | dropped | errors | p50 ms | p95 ms | p99 ms | VUs | Liferay cores p90 | host cores p90 | k6 cores p90 | old gen MB | full GC | |",
           "|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---|"]
    for r in ladders[k]:
        md.append("| " + " | ".join([r["target_rate"], r["achieved_iter_s"], r["req_s"], r["dropped_pct"] + " %", r["error_pct"] + " %",
                                     r["p50_ms"], r["p95_ms"], r["p99_ms"], r["max_vus"], r["liferay_cores_p90"], r["host_cores_p90"],
                                     r["k6_cores_p90"], r["heap_old_mb_max"], r["full_gc"],
                                     "**saturated**" if r["saturated"] == "1" else ("**a flow p95 > 2 s**" if worst_flow_p95(k, r["target_rate"]) >= 2000 else "")]) + " |")
    md.append("")
    # per-flow p95: one slow flow (login) can hide behind — or drag up — the overall p95
    flows = ["home", "content", "blog", "news", "search", "login"]
    per = []
    for r in ladders[k]:
        sj = os.path.join(RES, "stress", k, f"step-{r['target_rate']}.summary.json")
        if os.path.exists(sj):
            m = json.load(open(sj))["metrics"]
            per.append((r["target_rate"], [m.get(f"http_req_duration{{page:{p}}}", {}).get("values", {}) for p in flows]))
    present = [i for i, p in enumerate(flows) if any(v[i].get("count", v[i].get("p(95)")) for _, v in per)]
    if len(present) > 1:
        md += ["p95 ms per flow:", "", "| target it/s | " + " | ".join(flows[i] for i in present) + " |", "|---:|" + "---:|" * len(present)]
        for rate, vals in per:
            md.append(f"| {rate} | " + " | ".join(f"{vals[i]['p(95)']:,.0f}" if vals[i] else "–" for i in present) + " |")
        md.append("")
open(os.path.join(RES, "stress", "STEPS.md"), "w").write("\n".join(md))
print("wrote results/stress/STEPS.md")


# ---- 1. latency vs throughput: guest pages, and the mixed workload's slowest flow ----------
def curve_chart(keys, ycol, title, ylabel, name):
    fig, ax = plt.subplots(figsize=(10, 5.6))
    for i, k in enumerate(keys):
        rows = ladders[k]
        xs = [f(r, "req_s") for r in rows]
        ys = [worst_flow_p95(k, r["target_rate"]) if ycol == "worst" else f(r, ycol) for r in rows]
        ax.plot(xs, ys, color=SERIES[i], linewidth=2, marker="o", markersize=6, markeredgecolor=SURFACE, markeredgewidth=1.5, label=NAMES[k])
        j = max(range(len(xs)), key=lambda n: xs[n])
        ax.annotate(f"{xs[j]:,.0f} req/s", (xs[j], ys[j]), textcoords="offset points", xytext=(6, -12), fontsize=8.5, color=INK)
    ax.set_xscale("log")
    ax.set_yscale("log")
    style(ax, title, "achieved requests/s (log)", ylabel)
    ax.legend(frameon=False, fontsize=9.5, labelcolor=INK, loc="upper left")
    save(fig, name)


curve_chart([k for k in ("S0-origin-pages", "S3-origin-pages", "S4-edge-pages-light") if k in ladders], "p95_ms",
            "Guest pages: p95 while the request rate is stepped up", "p95 ms (log) — lower is better", "stress-latency-vs-throughput.png")
curve_chart([k for k in ("S0-origin-mix", "S3-origin-mix", "S4-edge-mix") if k in ladders], "worst",
            "Mixed workload: p95 of the slowest flow (search or login)", "slowest flow's p95 ms (log)", "stress-mix-slowest-flow.png")


# ---- 2. capacity per ladder: clean capacity (bar) + peak throughput (tick) -----------------
cap = [(k, clean(ladders[k]), peak(ladders[k])) for k in ORDER]
cap = [(k, c, pk) for k, c, pk in cap if c]
fig, ax = plt.subplots(figsize=(11, 0.62 * len(cap) + 1.9))
vals = [f(c, "req_s") for _, c, _ in cap]
bars = ax.barh(range(len(cap)), vals, height=0.6, color=[SERIES[2] if "edge" in k else SERIES[0] for k, _, _ in cap], edgecolor=SURFACE, linewidth=2)
peaks = [f(pk, "req_s") for _, _, pk in cap]
ax.scatter(peaks, range(len(cap)), marker="|", s=420, linewidths=2.5, color=INK, zorder=3, label="peak throughput reached")
ax.set_xscale("log")
ax.set_xlim(min(vals) / 2, max(peaks) * 3)
for i, (k, c, pk) in enumerate(cap):
    w = k.rsplit("-", 1)[1]
    unit = f" = {f(c, 'achieved_iter_s'):,.0f} {UNIT[w]}" if w in UNIT else ""
    ax.text(max(f(c, "req_s"), f(pk, "req_s")) * 1.12, i, f"{f(c, 'req_s'):,.0f} req/s{unit} · p95 {f(c, 'p95_ms'):,.0f} ms  |  peak {f(pk, 'req_s'):,.0f}",
            va="center", fontsize=9, color=INK)
ax.set_yticks(range(len(cap)))
ax.set_yticklabels([NAMES.get(k, k) for k, _, _ in cap])
ax.invert_yaxis()
style(ax, "Capacity per ladder", "requests/s (log)")
ax.set_title("Capacity per ladder", loc="left", fontsize=13, color=INK, fontweight="bold", pad=26)
ax.text(0, 1.015, "bar = clean capacity (< 1 % dropped, < 1 % errors, every flow p95 < 2 s)   |   tick = peak throughput reached with < 1 % errors",
        transform=ax.transAxes, fontsize=9, color=INK2)
ax.grid(False, axis="y")
save(fig, "stress-capacity.png")

# ---- 3. origin CPU vs throughput --------------------------------------------------------
origin = [k for k in ORDER if "origin" in k]
fig, ax = plt.subplots(figsize=(10, 5.4))
for i, k in enumerate(origin):
    rows = ladders[k]
    ax.plot([f(r, "req_s") for r in rows], [f(r, "liferay_cores_p90") for r in rows], color=SERIES[i % len(SERIES)], linewidth=2,
            marker="o", markersize=6, markeredgecolor=SURFACE, markeredgewidth=1.5, label=NAMES.get(k, k))
ax.axhline(20, color=INK2, linewidth=1, linestyle=":")
ax.text(0.01, 20.3, "20 cores = whole host", transform=ax.get_yaxis_transform(), fontsize=8.5, color=INK2)
ax.set_xscale("log")
style(ax, "Liferay container CPU while the request rate is stepped up", "achieved requests/s (log)", "CPU cores busy (p90 of 2 s samples)")
ax.legend(frameon=False, fontsize=9.5, labelcolor=INK, loc="center left", bbox_to_anchor=(1.01, 0.5))
save(fig, "stress-origin-cpu.png")
